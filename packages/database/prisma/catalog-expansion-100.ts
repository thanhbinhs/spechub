const modelSlugs = new Set(
  CATALOG_EXPANSION_100_DEVICES.map((device) => device.modelSlug),
);
if (
  CATALOG_EXPANSION_100_DEVICES.length !== 100 ||
  CATALOG_EXPANSION_100_MODULES.length !== 100 ||
  modelSlugs.size !== 100
) {
  throw new Error(
    "Catalog expansion must contain exactly 100 unique devices and 100 module profiles.",
  );
}

for (const [category, expectedCount] of Object.entries(
  expectedCategoryCounts,
) as Array<[CategorySlug, number]>) {
  const actualCount = CATALOG_EXPANSION_100_DEVICES.filter(
    (device) => device.categorySlug === category,
  ).length;
  if (actualCount !== expectedCount) {
    throw new Error(
      `Catalog expansion category ${category} has ${actualCount}/${expectedCount} devices.`,
    );
  }
}

for (const device of CATALOG_EXPANSION_100_DEVICES) {
  if (
    !device.sourceUrl.startsWith("https://") ||
    device.description.length < 220 ||
    device.launchPrice <= 0 ||
    device.weightG <= 0 ||
    device.modelSlug.startsWith("seed-")
  ) {
    throw new Error(`Incomplete real-device seed: ${device.modelSlug}.`);
  }
}
