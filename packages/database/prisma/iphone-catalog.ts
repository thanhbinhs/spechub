function slugify(value: string) {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function cameraModules(profile: CameraProfile) {
  const selfie = {
    role: "selfie",
    position: "front",
    megapixel:
      profile === "rear-3-selfie" ? 0.3 : profile === "rear-5-selfie" ? 0.3 : 7,
    aperture: profile.startsWith("fusion-48-pro-2025") ? "f/1.9" : "f/2.2",
    focalLength: 23,
    ois: false,
    af: profile.includes("2025"),
    video: profile.includes("2025")
      ? "4K Dolby Vision, Center Stage"
      : "1080p/4K",
  };
  const mainMp = profile.startsWith("fusion-48")
    ? 48
    : profile === "rear-2"
      ? 2
      : profile === "rear-3-selfie"
        ? 3
        : profile === "rear-5-selfie"
          ? 5
          : profile === "rear-8-selfie"
            ? 8
            : 12;
  const main = {
    role: "main",
    position: "rear",
    megapixel: mainMp,
    aperture: profile.startsWith("fusion-48") ? "f/1.6" : "f/1.8",
    focalLength: 26,
    ois: ![
      "rear-2",
      "rear-3-selfie",
      "rear-5-selfie",
      "rear-8-selfie",
    ].includes(profile),
    af: profile !== "rear-2",
    video: mainMp >= 12 ? "4K" : "1080p",
  };
  const result = [main] as Array<typeof main>;
  if (profile !== "rear-2") result.push(selfie);
  if (
    ["dual-12", "triple-12", "fusion-48-pro", "fusion-48-pro-2025"].includes(
      profile,
    )
  ) {
    result.push({
      role: "telephoto",
      position: "rear",
      megapixel: profile === "fusion-48-pro-2025" ? 48 : 12,
      aperture: profile === "fusion-48-pro-2025" ? "f/2.8" : "f/2.4",
      focalLength: profile === "fusion-48-pro-2025" ? 100 : 77,
      ois: true,
      af: true,
      video: "4K",
    });
  }
  if (
    [
      "dual-12-uw",
      "triple-12",
      "fusion-48-uw",
      "fusion-48-pro",
      "fusion-48-pro-2025",
    ].includes(profile)
  ) {
    result.push({
      role: "ultrawide",
      position: "rear",
      megapixel:
        profile === "fusion-48-pro-2025" || profile === "fusion-48-uw"
          ? 48
          : 12,
      aperture: "f/2.2",
      focalLength: 13,
      ois: false,
      af: profile.startsWith("fusion-48"),
      video: "4K",
    });
  }
  if (profile === "fusion-48" || profile === "fusion-48-uw") {
    result.push({
      role: "telephoto",
      position: "rear",
      megapixel: 12,
      aperture: "f/1.6",
      focalLength: 52,
      ois: true,
      af: true,
      video: "Cắt cảm biến 2x chất lượng quang học",
    });
  }
  return result;
}

function memoryStandardFor(year: number) {
  if (year <= 2009) return "lpddr";
  if (year <= 2012) return "lpddr2";
  if (year <= 2014) return "lpddr3";
  if (year <= 2017) return "lpddr4";
  if (year <= 2020) return "lpddr4x";
  if (year <= 2023) return "lpddr5";
  return "lpddr5x";
}

function parseStorageGb(variantName: string, fallback: number) {
  const matches = [...variantName.matchAll(/(\d+)\s*(TB|GB)/gi)];
  if (!matches.length) return fallback;
  const last = matches.at(-1)!;
  return Number(last[1]) * (last[2]?.toUpperCase() === "TB" ? 1024 : 1);
}

async function upsertBenchmarkResult(
  prisma: PrismaClient,
  data: {
    benchmarkId: string;
    benchmarkRunId: string;
    variantId: string;
    sourceId: string;
    score: number;
    subscore: string;
    testedAt: Date;
  },
) {
  const existing = await prisma.device_variant_benchmarks.findFirst({
    where: {
      benchmark_id: data.benchmarkId,
      device_variant_id: data.variantId,
      subscore_name: data.subscore,
    },
  });
  const values = {
    benchmark_run_id: data.benchmarkRunId,
    source_id: data.sourceId,
    score: data.score,
    tested_at: data.testedAt,
  };
  if (existing) {
    await prisma.device_variant_benchmarks.update({
      where: { id: existing.id },
      data: values,
    });
  } else {
    await prisma.device_variant_benchmarks.create({
      data: {
        ...values,
        benchmark_id: data.benchmarkId,
        device_variant_id: data.variantId,
        subscore_name: data.subscore,
      },
    });
  }
}

